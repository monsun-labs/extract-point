#!/usr/bin/env python3
"""Convert a tutorial notebook to Markdown + local media for Monsun Labs.

Uses nbconvert MarkdownExporter + FilesWriter. Does NOT execute the notebook.
Committed cell outputs (including embedded PNG/JPEG) are preserved and extracted.

Usage:
  python labs-publish/convert_notebook.py
  python labs-publish/convert_notebook.py --manifest labs-publish/manifest.yaml --out labs-publish/out
"""

from __future__ import annotations

import argparse
import hashlib
import re
import shutil
import subprocess
import sys
from pathlib import Path

import nbformat
import yaml
from nbconvert import MarkdownExporter
from nbconvert.writers import FilesWriter
from traitlets.config import Config

REPO_ROOT = Path(__file__).resolve().parents[1]


def _git_sha(repo: Path) -> str:
    try:
        out = subprocess.check_output(
            ["git", "rev-parse", "HEAD"],
            cwd=repo,
            text=True,
            stderr=subprocess.DEVNULL,
        )
        return out.strip()
    except (subprocess.CalledProcessError, FileNotFoundError):
        return "unknown"


def _load_manifest(path: Path) -> dict:
    data = yaml.safe_load(path.read_text(encoding="utf-8"))
    if not isinstance(data, dict):
        raise SystemExit(f"Manifest must be a mapping: {path}")
    required = ("slug", "notebook_path", "website", "title")
    missing = [k for k in required if k not in data]
    if missing:
        raise SystemExit(f"Manifest missing keys {missing}: {path}")
    return data


def _validate_media(repo: Path, media: list[dict]) -> list[dict]:
    """Return allowlisted media descriptors: src, dest, alt, inject, match."""
    items: list[dict] = []
    for entry in media or []:
        rel = entry.get("path")
        dest = entry.get("dest")
        if not rel or not dest:
            raise SystemExit(f"media entries require path and dest: {entry}")
        src = (repo / rel).resolve()
        if not str(src).startswith(str(repo.resolve())):
            raise SystemExit(f"media path escapes repo root: {rel}")
        if not src.is_file():
            raise SystemExit(f"media file missing: {rel}")
        dest_name = Path(dest).name
        if dest_name != dest or ".." in dest:
            raise SystemExit(f"media dest must be a plain filename: {dest}")
        items.append(
            {
                "src": src,
                "dest": dest_name,
                "alt": entry.get("alt") or dest_name,
                "inject": bool(entry.get("inject", True)),
                # Substring used to locate the related code cell in generated MD.
                "match": entry.get("match") or Path(rel).name,
            }
        )
    return items


def _build_index_with_body(manifest: dict, git_sha: str, body_md: str) -> str:
    """Single landing page: shell + converted notebook body (no manual edits)."""
    title = manifest["title"]
    summary = manifest.get("summary", "").strip()
    colab = manifest.get("colab_url", "")
    repo_url = manifest.get("repo_url", "")
    status = manifest.get("status", "early")
    sample = manifest.get("sample_data") or {}

    parts = [
        "---",
        "icon: lucide/crosshair",
        f"# Generated by labs-publish — source_sha: {git_sha}",
        "# Do not hand-edit this file; regenerate from the tutorial notebook.",
        "---",
        "",
        f"# {title}",
        "",
    ]
    if summary:
        parts.extend([summary, ""])
    if colab:
        parts.append(
            f"[![Open In Colab](https://colab.research.google.com/assets/colab-badge.svg)]({colab})"
        )
        parts.append("&nbsp;")
    if repo_url:
        parts.append(
            f"[View on GitHub :fontawesome-brands-github:]({repo_url}){{ .md-button }}"
        )
        parts.append("")
    parts.extend(
        [
            f"**Status:** {status}  ",
            f"**Source commit:** `{git_sha}`",
            "",
        ]
    )
    if sample:
        tag = sample.get("release_tag", "")
        grid = sample.get("grid", "")
        res = sample.get("resolution_deg", "")
        period = sample.get("period", "")
        size = sample.get("size_bytes", "")
        rel_link = (
            f"[`{tag}`]({repo_url}/releases/tag/{tag})"
            if repo_url and tag
            else f"`{tag}`"
        )
        parts.extend(
            [
                "## Sample data",
                "",
                "| Property | Value |",
                "|---|---|",
                f"| Release | {rel_link} |",
                f"| Grid | {grid} at {res}° |",
                f"| Period | {period} |",
                f"| Size | {size} bytes |",
                "",
            ]
        )
    parts.extend(
        [
            "---",
            "",
            "## Notebook",
            "",
            body_md.strip(),
            "",
            "---",
            "",
            "## Disclaimer",
            "",
            "For **education only**. Output is not certified for engineering design,",
            "regulatory submission, or operational decision-making.",
            "",
        ]
    )
    return "\n".join(parts)


def _rewrite_image_links(markdown: str, media_dirname: str) -> str:
    """Point nbconvert *_files/ image refs at media/."""
    return re.sub(
        r"\((?:[^)/]+_files)/([^)]+)\)",
        lambda m: f"({media_dirname}/{m.group(1)})",
        markdown,
    )


def _rewrite_repo_relative_links(markdown: str, repo_url: str, notebook_path: str) -> str:
    """Map notebook-relative repo paths to GitHub blob URLs (avoid broken site links)."""
    if not repo_url:
        return markdown
    nb_dir = Path(notebook_path).parent.as_posix()
    base = repo_url.rstrip("/") + "/blob/main/"

    def repl(match: re.Match[str]) -> str:
        label, target = match.group(1), match.group(2)
        if re.match(r"^[a-z]+://", target) or target.startswith("#") or target.startswith("/"):
            return match.group(0)
        if target.startswith("media/") or target.startswith("../media/"):
            return match.group(0)
        # Resolve relative to notebook directory, then normalize
        resolved = Path(nb_dir, target).as_posix()
        while "/../" in resolved:
            resolved = re.sub(r"[^/]+/\.\./", "", resolved, count=1)
        resolved = resolved.lstrip("./")
        return f"[{label}]({base}{resolved})"

    return re.sub(r"\[([^\]]+)\]\(([^)]+)\)", repl, markdown)


def _local_image_refs(markdown: str, media_dirname: str) -> list[str]:
    """Return media filenames referenced by local Markdown image/link targets."""
    pattern = rf"\((?:\.\./)?{re.escape(media_dirname)}/([^)\s]+)\)"
    return [Path(m).name for m in re.findall(pattern, markdown)]


def _inject_allowlisted_media_refs(
    markdown: str,
    media_items: list[dict],
    media_dirname: str,
) -> str:
    """Insert Markdown image refs for allowlisted files that lack committed outputs.

    nbconvert only extracts display_data/execute_result images. Cells that use
    ``Image(filename=...)`` without committed image MIME data need an explicit
    ref once the file has been copied into media/.
    """
    existing = set(_local_image_refs(markdown, media_dirname))
    result = markdown
    for item in media_items:
        if not item["inject"]:
            continue
        dest = item["dest"]
        if dest in existing:
            continue
        needle = item["match"]
        img_md = f"\n\n![{item['alt']}]({media_dirname}/{dest})\n"
        # Prefer placing after the first fenced block that mentions the asset.
        fence_pat = re.compile(
            rf"(```[^\n]*\n[\s\S]*?{re.escape(needle)}[\s\S]*?```)",
        )
        m = fence_pat.search(result)
        if m:
            insert_at = m.end()
            result = result[:insert_at] + img_md + result[insert_at:]
            existing.add(dest)
            continue
        # Fallback: append under a generated figures section once.
        if "## Published figures" not in result:
            result += "\n\n## Published figures\n"
        result += img_md
        existing.add(dest)
    return result


def _validate_image_refs_resolve(
    markdown: str,
    media_out: Path,
    media_dirname: str,
) -> list[str]:
    """Return dangling local media references (must be empty)."""
    missing: list[str] = []
    for name in _local_image_refs(markdown, media_dirname):
        if not (media_out / name).is_file():
            missing.append(name)
    return missing


def convert(
    *,
    repo: Path,
    manifest_path: Path,
    out_dir: Path,
) -> Path:
    manifest = _load_manifest(manifest_path)
    notebook_path = repo / manifest["notebook_path"]
    if not notebook_path.is_file():
        raise SystemExit(f"Notebook not found: {notebook_path}")

    website = manifest["website"]
    media_dirname = website.get("media_dirname", "media")
    body_name = website.get("generated_body", "body.md")
    index_name = website.get("landing_index", "index.md")

    git_sha = _git_sha(repo)
    media_items = _validate_media(repo, manifest.get("media") or [])

    out_dir = out_dir.resolve()
    if out_dir.exists():
        shutil.rmtree(out_dir)
    media_out = out_dir / media_dirname
    media_out.mkdir(parents=True)

    nb = nbformat.read(notebook_path, as_version=4)
    # Safety: never attach ExecutePreprocessor
    c = Config()
    c.MarkdownExporter.exclude_input_prompt = False
    c.MarkdownExporter.exclude_output_prompt = False
    exporter = MarkdownExporter(config=c)
    # Force resources to write under media/
    resources = {
        "metadata": {"path": str(notebook_path.parent), "name": notebook_path.stem},
        "output_files_dir": media_dirname,
    }
    body, resources = exporter.from_notebook_node(nb, resources=resources)

    # Write extracted binary outputs into media/
    outputs = resources.get("outputs") or {}
    for rel_name, data in outputs.items():
        # nbconvert may key as "media/foo.png" or "foo.png"
        name = Path(rel_name).name
        target = media_out / name
        target.write_bytes(data)

    # Copy allowlisted static media
    for item in media_items:
        shutil.copy2(item["src"], media_out / item["dest"])

    body = _rewrite_image_links(body, media_dirname)
    body = _rewrite_repo_relative_links(
        body,
        str(manifest.get("repo_url") or ""),
        str(manifest["notebook_path"]),
    )

    # Prefer media/dest when body mentions dest basename as a bare link target
    for item in media_items:
        dest_name = item["dest"]
        body = body.replace(f"]({dest_name})", f"]({media_dirname}/{dest_name})")

    body = _inject_allowlisted_media_refs(body, media_items, media_dirname)

    missing = _validate_image_refs_resolve(body, media_out, media_dirname)
    if missing:
        raise SystemExit(
            "Generated Markdown references missing media files: "
            + ", ".join(sorted(set(missing)))
        )

    body_path = out_dir / body_name
    body_path.write_text(body, encoding="utf-8")

    replace_index = bool(website.get("replace_index", False))
    if replace_index:
        index_md = _build_index_with_body(manifest, git_sha, body)
        (out_dir / index_name).write_text(index_md, encoding="utf-8")

    # Provenance sidecar
    digest = hashlib.sha256(body.encode("utf-8")).hexdigest()
    referenced = sorted(set(_local_image_refs(body, media_dirname)))
    provenance = {
        "slug": manifest["slug"],
        "git_sha": git_sha,
        "notebook": str(manifest["notebook_path"]),
        "body_sha256": digest,
        "media_files": sorted(p.name for p in media_out.iterdir() if p.is_file()),
        "media_referenced": referenced,
        "executed": False,
        "replace_index": replace_index,
    }
    (out_dir / "provenance.yaml").write_text(
        yaml.safe_dump(provenance, sort_keys=True),
        encoding="utf-8",
    )

    return out_dir


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--manifest",
        type=Path,
        default=REPO_ROOT / "labs-publish" / "manifest.yaml",
    )
    parser.add_argument(
        "--out",
        type=Path,
        default=REPO_ROOT / "labs-publish" / "out",
    )
    parser.add_argument(
        "--repo",
        type=Path,
        default=REPO_ROOT,
        help="Tutorial repository root",
    )
    args = parser.parse_args(argv)

    out = convert(repo=args.repo.resolve(), manifest_path=args.manifest.resolve(), out_dir=args.out)
    print(f"Wrote publish artifacts to {out}")
    index_path = out / "index.md"
    if index_path.exists():
        print(f"  index: {index_path}")
    else:
        print("  index: (skipped; replace_index=false)")
    print(f"  body:  {out / 'body.md'}")
    print(f"  media: {out / 'media'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
